-- Run in Supabase SQL Editor before starting the pipeline.

create table if not exists public.anomalies (
    id bigint generated by default as identity primary key,
    region text not null,
    ts timestamp without time zone not null,
    mw double precision not null,
    expected_mw double precision not null,
    z_score double precision not null,
    severity text not null check (severity in ('WARNING', 'CRITICAL')),
    alerted boolean not null default false,
    created_at timestamptz not null default now(),
    constraint anomalies_region_ts_unique unique (region, ts)
);

-- JDBC writes here first; the pipeline merges this into anomalies.
create table if not exists public.anomalies_stage (
    run_id text not null,
    region text not null,
    ts timestamp without time zone not null,
    mw double precision not null,
    expected_mw double precision not null,
    z_score double precision not null,
    severity text not null
);

create index if not exists anomalies_region_ts_idx
    on public.anomalies (region, ts desc);

-- Dashboard summary view. The API key used by the dashboard must be allowed
-- to SELECT anomalies and this view through RLS.
create or replace view public.anomaly_summary
with (security_invoker = true) as
select region, severity, count(*)::bigint as anomaly_count
from public.anomalies
group by region, severity;

alter table public.anomalies enable row level security;

-- Example read-only policy for the dashboard's anon/publishable key.
-- For a private dashboard, replace this with authenticated-user policies.
drop policy if exists "public can read anomalies" on public.anomalies;
create policy "public can read anomalies"
    on public.anomalies for select
    to anon
    using (true);

grant select on public.anomalies to anon;
grant select on public.anomaly_summary to anon;
grant usage, select on sequence public.anomalies_id_seq to anon;

-- Enable Supabase Realtime for the table if it is not already included.
do $$
begin
    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'anomalies'
    ) then
        alter publication supabase_realtime add table public.anomalies;
    end if;
end
$$;
